# Sets up one iOS build configuration pair and one shared scheme per environment.
# Idempotent: safe to run again after renaming the app or adding an environment.
#
#   bundle exec ruby scripts/ios/configure-environments.rb
#
# Result (see docs/environments.md):
#   configurations  Debug-Dev  Release-Dev  Debug-Staging  Release-Staging  Debug-Prod  Release-Prod
#   schemes         <App>-Dev  <App>-Staging  <App>-Prod
#   xcconfig        ios/Config/<Env>.xcconfig            environment values (bundle id suffix, name, icon)
#                   ios/Config/<Debug|Release>-<Env>.xcconfig  includes the Pods xcconfig + the env file
require 'fileutils'
require 'json'
require 'xcodeproj'

# Read every file as UTF-8, whatever the shell's locale (comments in build.gradle aren't ASCII).
Encoding.default_external = Encoding::UTF_8

ROOT = File.expand_path('../..', __dir__)
APP_JSON = JSON.parse(File.read(File.join(ROOT, 'app.json')))
APP = APP_JSON['name']
DISPLAY = APP_JSON['displayName'] || APP
PROJECT_PATH = File.join(ROOT, 'ios', "#{APP}.xcodeproj")
CONFIG_DIR = File.join(ROOT, 'ios', 'Config')
BASE_BUNDLE_ID = ENV.fetch('BASE_BUNDLE_ID') { nil }

# Values from .env.<env> that the native project needs (ADR 0010, 0020): URL scheme, link domain, push and
# Sign in with Apple entitlements, Google sign-in's URL scheme.
def read_env(name)
  path = File.join(ROOT, ".env.#{name.downcase}")
  abort("Missing #{path}. Copy .env.example.") unless File.exist?(path)
  File.readlines(path).each_with_object({}) do |line, values|
    next unless (match = line.match(/\A\s*(?:export\s+)?([A-Za-z_][\w.-]*)\s*=\s*['"]?(.*?)['"]?\s*\z/))
    values[match[1]] = match[2]
  end
end

ENVIRONMENTS = [
  { name: 'Dev', suffix: '.dev', display: "#{DISPLAY} Dev", icon: 'AppIcon-Dev' },
  { name: 'Staging', suffix: '.staging', display: "#{DISPLAY} Staging", icon: 'AppIcon-Staging' },
  { name: 'Prod', suffix: '', display: DISPLAY, icon: 'AppIcon' },
].freeze

project = Xcodeproj::Project.open(PROJECT_PATH)
target = project.targets.find { |t| t.name == APP } or abort("No target named #{APP}")

# Bundle id: BASE_BUNDLE_ID env var, else Android's applicationId, so both platforms share one id.
gradle = File.read(File.join(ROOT, 'android', 'app', 'build.gradle'))
android_id = gradle[/applicationId\s+"([^"]+)"/, 1]
bundle_prefix = BASE_BUNDLE_ID || android_id or abort('Set BASE_BUNDLE_ID or applicationId in android/app/build.gradle')

# 1. xcconfig files.
config_group = project.main_group.find_subpath('Config', true)
config_group.set_source_tree('<group>')
config_group.set_path('Config')

def write_if_changed(path, content)
  return if File.exist?(path) && File.read(path) == content
  File.write(path, content)
end

ENVIRONMENTS.each do |env|
  values = read_env(env[:name])
  scheme = values['APP_SCHEME'].to_s
  abort(".env.#{env[:name].downcase} needs APP_SCHEME (e.g. myapp-dev)") if scheme.empty?

  # Entitlements only for capabilities that are switched on: both need a paid Apple team, so adding
  # them unconditionally would break signing with a free account.
  entitlements = {}
  domain = values['APP_LINK_DOMAIN'].to_s
  entitlements['com.apple.developer.associated-domains'] = ["applinks:#{domain}"] unless domain.empty?
  aps = values['IOS_APS_ENVIRONMENT'].to_s
  entitlements['aps-environment'] = aps unless aps.empty?
  # @social-start
  # Sign in with Apple (ADR 0020): also needs the capability on the App ID in your Apple account.
  entitlements['com.apple.developer.applesignin'] = ['Default'] if values['IOS_APPLE_SIGN_IN'] == 'true'
  # @social-end
  entitlements_rel = "#{APP}/#{APP}-#{env[:name]}.entitlements"
  entitlements_path = File.join(ROOT, 'ios', entitlements_rel)
  if entitlements.empty?
    FileUtils.rm_f(entitlements_path)
  else
    Xcodeproj::Plist.write_to_path(entitlements, entitlements_path)
  end

  # Extra build settings for optional modules (one line each).
  extra_settings = []
  # @social-start
  # Google sign-in returns to the app through the iOS client id, reversed, as a URL scheme. Without a
  # client id the slot repeats the app's own scheme, so Info.plist stays the same in every environment.
  google_ios = values['GOOGLE_IOS_CLIENT_ID'].to_s
  extra_settings << "GOOGLE_URL_SCHEME = #{google_ios.empty? ? scheme : google_ios.split('.').reverse.join('.')}"
  # @social-end

  write_if_changed(File.join(CONFIG_DIR, "#{env[:name]}.xcconfig"), <<~XC)
    // Environment: #{env[:name].downcase}. Generated by scripts/ios/configure-environments.rb from
    // .env.#{env[:name].downcase}: change values there and run the script again.
    APP_ENV = #{env[:name].downcase}
    BUNDLE_ID_SUFFIX = #{env[:suffix]}
    APP_DISPLAY_NAME = #{env[:display]}
    ASSETCATALOG_COMPILER_APPICON_NAME = #{env[:icon]}
    APP_URL_SCHEME = #{scheme}
    #{extra_settings.join("\n")}
    #{entitlements.empty? ? '' : "CODE_SIGN_ENTITLEMENTS = #{entitlements_rel}"}
  XC
  %w[Debug Release].each do |kind|
    name = "#{kind}-#{env[:name]}"
    # React Native only adds the Swift DEBUG condition to a configuration named exactly "Debug", so the
    # custom debug configurations set it here. Without it, `#if DEBUG` is false and the app skips Metro.
    debug_flags = kind == 'Debug' ? "SWIFT_ACTIVE_COMPILATION_CONDITIONS = $(inherited) DEBUG\n" : ''
    write_if_changed(File.join(CONFIG_DIR, "#{name}.xcconfig"), <<~XC)
      // #{name}: CocoaPods settings first, then the environment.
      #include? "../Pods/Target Support Files/Pods-#{APP}/Pods-#{APP}.#{name.downcase}.xcconfig"
      #include "#{env[:name]}.xcconfig"
      #{debug_flags}
    XC
  end
end

file_refs = Dir[File.join(CONFIG_DIR, '*.xcconfig')].sort.to_h do |path|
  base = File.basename(path)
  ref = config_group.files.find { |f| f.path == base } || config_group.new_reference(base)
  [base, ref]
end

# 2. Build configurations (project + target), duplicated from the template's Debug/Release.
def ensure_config(project, list, name, template_name)
  existing = list.build_configurations.find { |c| c.name == name }
  return existing if existing
  template = list.build_configurations.find { |c| c.name == template_name } ||
             list.build_configurations.find { |c| c.name.start_with?(template_name) }
  config = project.new(Xcodeproj::Project::Object::XCBuildConfiguration)
  config.name = name
  config.build_settings = Marshal.load(Marshal.dump(template.build_settings))
  config.base_configuration_reference = template.base_configuration_reference
  list.build_configuration_list.build_configurations << config
  config
end

[project, target].each do |owner|
  ENVIRONMENTS.each do |env|
    %w[Debug Release].each { |kind| ensure_config(project, owner, "#{kind}-#{env[:name]}", kind) }
  end
end

target.build_configurations.each do |config|
  next unless (match = config.name.match(/\A(Debug|Release)-(\w+)\z/))
  config.base_configuration_reference = file_refs["#{config.name}.xcconfig"]
  settings = config.build_settings
  settings['PRODUCT_BUNDLE_IDENTIFIER'] = "#{bundle_prefix}$(BUNDLE_ID_SUFFIX)"
  # Let the xcconfig decide the icon set.
  settings.delete('ASSETCATALOG_COMPILER_APPICON_NAME')
end

# Drop the environment-less Debug/Release once the env configurations exist.
[project, target].each do |owner|
  owner.build_configuration_list.build_configurations
       .select { |c| %w[Debug Release].include?(c.name) }
       .each(&:remove_from_project)
end
project.build_configuration_list.default_configuration_name = 'Release-Prod'
target.build_configuration_list.default_configuration_name = 'Release-Prod'

# 3. Info.plist reads the display name from the xcconfig.
plist_path = File.join(ROOT, 'ios', APP, 'Info.plist')
plist = Xcodeproj::Plist.read_from_path(plist_path)
plist['CFBundleDisplayName'] = '$(APP_DISPLAY_NAME)'
# Deep links: the scheme comes from the environment's xcconfig (APP_SCHEME in .env.<env>).
plist['CFBundleURLTypes'] = [
  { 'CFBundleURLName' => '$(PRODUCT_BUNDLE_IDENTIFIER)', 'CFBundleURLSchemes' => ['$(APP_URL_SCHEME)'] },
  # @social-start
  # [bareship] Google sign-in callback (ADR 0020): the reversed iOS client id from .env.<env>.
  { 'CFBundleURLName' => 'google-sign-in', 'CFBundleURLSchemes' => ['$(GOOGLE_URL_SCHEME)'] },
  # @social-end
]
# Push: lets Firebase Messaging receive data messages in the background.
plist['UIBackgroundModes'] = (Array(plist['UIBackgroundModes']) | ['remote-notification'])
Xcodeproj::Plist.write_to_path(plist, plist_path)

# 3b. Firebase is optional (ADR 0010): copy ios/Config/Firebase/<env>/GoogleService-Info.plist into the
# app when it exists, and upload Crashlytics symbols only for Release builds that have it. Replaces the
# "[RNFB] Crashlytics Configuration" phase, which react-native.config.js turns off.
def ensure_script_phase(project, target, name, script, inputs: [], outputs: [], after: nil)
  phase = target.shell_script_build_phases.find { |p| p.name == name } || target.new_shell_script_build_phase(name)
  phase.shell_script = script
  phase.input_paths = inputs
  phase.output_paths = outputs
  phase.always_out_of_date = '1'
  phase.show_env_vars_in_log = '0'
  if after
    target.build_phases.delete(phase)
    index = target.build_phases.index(after) || (target.build_phases.size - 1)
    target.build_phases.insert(index + 1, phase)
  end
  phase
end

ensure_script_phase(project, target, '[bareship] Copy Firebase config', <<~SH, after: target.resources_build_phase)
  # Firebase is optional (ADR 0010). Put this environment's file at ios/Config/Firebase/<env>/.
  SRC="${PROJECT_DIR}/Config/Firebase/${APP_ENV}/GoogleService-Info.plist"
  DEST="${TARGET_BUILD_DIR}/${UNLOCALIZED_RESOURCES_FOLDER_PATH}/GoogleService-Info.plist"
  if [ -f "$SRC" ]; then
    cp "$SRC" "$DEST"
    echo "Firebase: using Config/Firebase/${APP_ENV}/GoogleService-Info.plist"
  else
    rm -f "$DEST"
    echo "Firebase: not set up for ${APP_ENV} (no Config/Firebase/${APP_ENV}/GoogleService-Info.plist)"
  fi
SH

ensure_script_phase(project, target, '[bareship] Crashlytics symbols', <<~SH,
  # Uploads dSYMs so Crashlytics can symbolicate native crashes. Release builds with Firebase only.
  case "${CONFIGURATION}" in Release-*) ;; *) exit 0 ;; esac
  if [ ! -f "${TARGET_BUILD_DIR}/${UNLOCALIZED_RESOURCES_FOLDER_PATH}/GoogleService-Info.plist" ]; then
    echo "Crashlytics: Firebase not set up for ${APP_ENV}, skipping dSYM upload"
    exit 0
  fi
  "${PODS_ROOT}/FirebaseCrashlytics/run"
SH
  inputs: [
    '${DWARF_DSYM_FOLDER_PATH}/${DWARF_DSYM_FILE_NAME}',
    '${DWARF_DSYM_FOLDER_PATH}/${DWARF_DSYM_FILE_NAME}/Contents/Resources/DWARF/${PRODUCT_NAME}',
    '${DWARF_DSYM_FOLDER_PATH}/${DWARF_DSYM_FILE_NAME}/Contents/Info.plist',
    '$(TARGET_BUILD_DIR)/$(UNLOCALIZED_RESOURCES_FOLDER_PATH)/GoogleService-Info.plist',
    '$(TARGET_BUILD_DIR)/$(EXECUTABLE_PATH)',
  ])

# 4. The template's LaunchScreen.storyboard is replaced by BootSplash.storyboard.
project.files.select { |f| f.path.to_s.end_with?('LaunchScreen.storyboard') }.each do |ref|
  target.resources_build_phase.files.select { |bf| bf.file_ref == ref }.each(&:remove_from_project)
  ref.remove_from_project
end

project.save

# 5. One shared scheme per environment; remove the template's single scheme.
schemes_dir = Xcodeproj::XCScheme.shared_data_dir(PROJECT_PATH)
FileUtils.rm_f(File.join(schemes_dir, "#{APP}.xcscheme"))
ENVIRONMENTS.each do |env|
  scheme = Xcodeproj::XCScheme.new
  scheme.add_build_target(target)
  scheme.set_launch_target(target)
  scheme.launch_action.build_configuration = "Debug-#{env[:name]}"
  scheme.test_action.build_configuration = "Debug-#{env[:name]}"
  scheme.analyze_action.build_configuration = "Debug-#{env[:name]}"
  scheme.profile_action.build_configuration = "Release-#{env[:name]}"
  scheme.archive_action.build_configuration = "Release-#{env[:name]}"
  scheme.save_as(PROJECT_PATH, "#{APP}-#{env[:name]}", true)
end

puts "✓ #{APP}: #{ENVIRONMENTS.size} environments, bundle id #{bundle_prefix}$(BUNDLE_ID_SUFFIX)"
puts '  Next: bundle exec pod install --project-directory=ios'
